const markdownTopic = (node, level = 0) => {
  const prefix = `${"  ".repeat(level)}- `;
  const childText = node.children?.attached?.map((child) => markdownTopic(child, level + 1)).join("\n") ?? "";
  return `${prefix}${node.title}${childText ? `\n${childText}` : ""}`;
};

