let sequence = 0;
const id = (prefix = "topic") => `${prefix}-${String(++sequence).padStart(4, "0")}`;

const topic = (title, children = [], options = {}) => ({
  id: id("topic"),
  class: "topic",
  title,
  ...(options.notes ? { notes: { plain: { content: options.notes } } } : {}),
  ...(children.length ? { children: { attached: children } } : {}),
});

const branch = (title, items, notes) => topic(
  title,
  items.map((item) => Array.isArray(item)
    ? branch(item[0], item[1], item[2])
    : typeof item === "string"
      ? topic(item)
      : topic(item.title, item.children ?? [], { notes: item.notes })),
  { notes },
);

